def _metric_name(f: Facts, code: str) -> str:
    """议题映射指标的名称；派生指标（如 S19_COV）不在采集表指标表中，单独兜底。"""
    m = f.metric(code)
    if m is not None and m.name:
        return m.name
    return {"S19_COV": "供应商 ESG 评估覆盖率"}.get(code, code)


