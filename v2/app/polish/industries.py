PACKS: dict[str, IndustryPack] = {
    p.key: p for p in [MANUFACTURING, TECHNOLOGY, RETAIL, LOGISTICS, REAL_ESTATE, BANKING, SERVICES, UNKNOWN]
}

# 采集表的行业值可能未归一（如「贸易」「建筑」），在这里兜底映射
ALIASES: dict[str, str] = {
    "贸易": "retail",
    "批发": "retail",
    "餐饮": "retail",
    "建筑": "real_estate",
    "物业": "real_estate",
    "运输": "logistics",
    "航运": "logistics",
    "金融": "banking",
    "保险": "banking",
    "资讯科技": "technology",
    "互联网": "technology",
    "制造": "manufacturing",
}


def get_pack(industry_key: str | None, industry_label: str | None = None) -> IndustryPack:
    key = (industry_key or "").strip().lower()
    if key in PACKS:
        return PACKS[key]
    label = (industry_label or "").strip()
    if label in ALIASES:
        return PACKS[ALIASES[label]]
    for k, p in PACKS.items():
        if label and (p.label in label or label in p.label):
            return p
    return PACKS["unknown"]
